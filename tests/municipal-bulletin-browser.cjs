const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');const assert=require('node:assert/strict');const fs=require('node:fs');
(async()=>{const browser=await chromium.launch({channel:'msedge',headless:true});try{
const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[],now=Date.now(),date=new Date(now).toISOString();let empty=false;
page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{window.printCalls=0;window.print=()=>window.printCalls++;});
const readings=[{dateTime:new Date(now-23.5*3600000).toISOString(),level:100},{dateTime:date,level:118}];
await page.route('https://**/*',route=>{
 const url=route.request().url();
 if(empty)return route.abort();
 if(url.includes('resources.cemaden.gov.br/dados/311_24.json'))return route.fulfill({contentType:'text/javascript',body:`estacoes(${JSON.stringify([{atualizado:date,estacao:[{uf:'TO',status:0,idtipoestacao:1,codestacao:'1',cidade:'Palmas',nomeestacao:'Posto Palmas',acumulado:21.5,latitude:-10.184,longitude:-48.333}]}])});`});
 if(url.includes('/estacoes/T'))return route.fulfill({json:[]});
 if(url.includes('HidroInventario'))return route.fulfill({contentType:'text/xml',body:'<root><Table><Codigo>123</Codigo><Nome>Estação Palmas</Nome><RioNome>Tocantins</RioNome><nmMunicipio>Palmas</nmMunicipio><Latitude>-10.184</Latitude><Longitude>-48.333</Longitude></Table></root>'});
 if(url.includes('DadosHidrometeorologicos'))return route.fulfill({contentType:'text/xml',body:`<root>${readings.map(row=>`<DadosHidrometereologicos><Nivel>${row.level}</Nivel><DataHora>${row.dateTime}</DataHora></DadosHidrometereologicos>`).join('')}</root>`});
 if(url.includes('api.open-meteo.com'))return route.fulfill({json:{hourly:{time:Array.from({length:72},(_,i)=>Math.floor(now/1000)+i*3600),temperature_2m:Array(72).fill(31),relative_humidity_2m:Array(72).fill(55),wind_speed_10m:Array(72).fill(12),wind_direction_10m:Array(72).fill(90),wind_gusts_10m:Array(72).fill(18),precipitation:Array(72).fill(.5)}}});
 if(url.includes('statistics/years'))return route.fulfill({json:[2026]});
 if(url.includes('/months'))return route.fulfill({json:[9]});
 if(url.includes('/statistics/area/'))return route.fulfill({json:{areaHa:123.45}});
 return route.abort();
});
await page.route('**/data/river-summary.json*',route=>route.fulfill({json:{status:'error',stations:[],attemptedAt:date}}));
await page.route('**/data/fire-history.json*',route=>route.fulfill({json:empty?{status:'error',points:[]}:{status:'ready',updatedAt:date,coverageStart:new Date(now-8*86400000).toISOString(),coverageEnd:date,points:[{latitude:-10.184,longitude:-48.333,detectedAt:new Date(now-3600000).toISOString(),city:'Palmas',satellite:'A'}]}}));
await page.route('**/dados-monitoramento.json*',route=>route.fulfill({json:empty?{atualizado_em:null}:{atualizado_em:date,resumo:{alertas_cemaden_to:0,avisos_inmet_to_hoje:0},focos_calor:{status:'ok',quantidade24h:0,atualizadoEm:date,pontos_24h:[]}}}));
await page.goto('http://127.0.0.1:4196/Monitoramento-site/',{waitUntil:'domcontentloaded'});
await page.getByRole('button',{name:'Consultar novamente',exact:true,includeHidden:true}).waitFor({state:'attached',timeout:55000});
await page.locator('#municipality-picker').selectOption('1721000');
await page.locator('.municipal-weather').waitFor();
await page.locator('.municipal-panel').getByText('123,5 ha',{exact:true}).waitFor();
await page.getByRole('button',{name:'Gerar Resumo Municipal',exact:true}).click();
await page.getByRole('button',{name:'Imprimir / Salvar PDF',exact:true}).waitFor();
await page.waitForFunction(()=>window.printCalls===1);
assert.equal(await page.locator('.municipal-print-page').count(),4);
assert.equal(await page.locator('.municipal-document-map').count(),5);
assert.match(await page.locator('.municipal-document').innerText(),/21,5 mm/);
assert.match(await page.locator('.municipal-document').innerText(),/123,45 ha/);
assert.match(await page.locator('.municipal-document').innerText(),/118 cm/);
await page.emulateMedia({media:'print'});
assert.equal(await page.locator('.municipal-document').evaluate(node=>getComputedStyle(node).visibility),'visible');
assert.equal(await page.locator('.municipal-document-toolbar').isVisible(),false);
assert.equal(await page.locator('.municipal-print-page').evaluateAll(nodes=>nodes.every(node=>node.getBoundingClientRect().height<1031)),true,'Each page fits printable A4 height');
fs.mkdirSync('tmp/pdfs',{recursive:true});
await page.pdf({path:'tmp/pdfs/municipal-completo.pdf',format:'A4',printBackground:true,preferCSSPageSize:true});
await page.emulateMedia({media:'screen'});
await page.keyboard.press('Escape');
assert.equal(await page.locator('.municipal-bulletin-preview').count(),0);
assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Gerar Resumo Municipal');
empty=true;await page.reload({waitUntil:'domcontentloaded'});
await page.getByRole('button',{name:'Consultar novamente',exact:true,includeHidden:true}).waitFor({state:'attached',timeout:55000});
await page.locator('#municipality-picker').selectOption('1702109');
await page.getByRole('button',{name:'Gerar Resumo Municipal',exact:true}).click();
await page.waitForFunction(()=>window.printCalls===1);
assert.match(await page.locator('.municipal-document').innerText(),/Araguaína/);
assert.match(await page.locator('.municipal-document').innerText(),/Indisponível/);
await page.emulateMedia({media:'print'});
await page.pdf({path:'tmp/pdfs/municipal-sem-dados.pdf',format:'A4',printBackground:true,preferCSSPageSize:true});
await page.emulateMedia({media:'screen'});
await page.setViewportSize({width:390,height:844});
assert.equal(await page.locator('.municipal-bulletin-preview').evaluate(node=>node.scrollWidth<=node.clientWidth),true);
await page.getByRole('button',{name:'Voltar ao mapa',exact:true}).click();
await page.setViewportSize({width:1440,height:1100});
await page.getByRole('button',{name:'Modo Operacional',exact:true}).click();
const box=await page.locator('.operational-active .public-map').boundingBox();
await page.locator('.operational-active .public-map').click({position:{x:box.width/2,y:box.height/2}});
await page.getByRole('button',{name:'Gerar Resumo Municipal',exact:true}).click();
await page.waitForFunction(()=>window.printCalls===2);
await page.keyboard.press('Escape');
assert.equal(await page.locator('.municipal-bulletin-preview').count(),0);
assert.equal(await page.locator('.operational-active').count(),1,'Escape closes PDF preview and preserves operational workspace');
await page.getByRole('button',{name:'Modo Público',exact:true}).click();
assert.deepEqual(errors,[]);
console.log('Municipal bulletin: populated/missing data PDFs, maps, chart, print visibility, auto-print, focus and mobile passed.');
}finally{await browser.close()}})();
