const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');const assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({channel:'msedge',headless:true});try{
const page=await browser.newPage({viewport:{width:1920,height:1080}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.QA_URL||'http://127.0.0.1:4196/Monitoramento-site/',{waitUntil:'domcontentloaded'});
await page.getByRole('button',{name:'Modo Operacional',exact:true}).click();
await page.locator('.operational-active').waitFor();
assert.equal(await page.getByRole('button',{name:'Iniciar rotação',exact:true}).getAttribute('aria-pressed'),'false');
assert.equal(await page.locator('.operational-themes button[aria-pressed=true]').innerText(),'Visão estadual');
assert.equal(await page.locator('.operational-indicators button').count(),4);
assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Modo Público');
assert.equal(await page.evaluate(()=>document.body.style.overflow),'hidden');
await page.getByLabel('Intervalo da rotação').selectOption('15');
await page.getByRole('button',{name:'Iniciar rotação',exact:true}).click();
await page.waitForTimeout(15500);
assert.equal(await page.locator('.operational-themes button[aria-pressed=true]').innerText(),'Hidrologia');
await page.locator('.operational-themes').getByRole('button',{name:'Fogo',exact:true}).click();
await page.getByRole('button',{name:'Iniciar rotação',exact:true}).waitFor();
await page.clock.install();
await page.getByLabel('Intervalo da rotação').selectOption('60');
await page.getByRole('button',{name:'Iniciar rotação',exact:true}).click();
await page.clock.fastForward(59000);
assert.equal(await page.locator('.operational-themes button[aria-pressed=true]').innerText(),'Fogo');
await page.clock.fastForward(1100);
assert.equal(await page.locator('.operational-themes button[aria-pressed=true]').innerText(),'Seca');
await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
await page.clock.fastForward(65000);
assert.equal(await page.locator('.operational-themes button[aria-pressed=true]').innerText(),'Seca','Hidden tab suspends rotation');
await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'));});
await page.clock.fastForward(61000);
assert.equal(await page.locator('.operational-themes button[aria-pressed=true]').innerText(),'Visão estadual');
await page.locator('.public-map').click({position:{x:20,y:200}});
await page.getByRole('button',{name:'Iniciar rotação',exact:true}).waitFor();
await page.clock.resume();
await page.locator('.operational-themes').getByRole('button',{name:'Visão estadual',exact:true}).click();
assert.equal(await page.locator('.geo-toolbar').isVisible(),false,'No duplicated theme navigation in operational view');
await page.locator('.operational-active').screenshot({path:'tmp/operational-desktop.png'});
await page.setViewportSize({width:2560,height:1440});
assert.equal(await page.locator('.operational-active').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
await page.locator('.operational-active').screenshot({path:'tmp/operational-videowall.png'});
await page.keyboard.press('Escape');
assert.equal(await page.locator('.operational-active').count(),0);
assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Modo Operacional');
assert.notEqual(await page.evaluate(()=>document.body.style.overflow),'hidden');
assert.equal(await page.locator('.geo-layer-switch button[aria-pressed=true]').innerText(),'Visão geral');
await page.getByRole('button',{name:'Modo Operacional',exact:true}).click();
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
assert.equal(await page.locator('.operational-active').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
await page.locator('.operational-console').screenshot({path:'tmp/operational-mobile.png'});
await page.getByRole('button',{name:'Modo Público',exact:true}).click();
assert.deepEqual(errors,[]);
console.log('Operational browser: enter/exit, focus, 15s rotation, manual pause, 1920px/mobile, restore public theme passed.');
}finally{await browser.close()}})();
