import assert from 'node:assert/strict';
import {buildStateSituation, situationThemes} from '../frontend/src/services/stateSituation.js';
const now=Date.now(),date=new Date(now).toISOString();
const features=[{type:'Feature',properties:{codarea:'1',nome:'Teste'},geometry:{type:'Polygon',coordinates:[[[-49,-11],[-47,-11],[-47,-9],[-49,-9],[-49,-11]]]}}];
const rain={state:'ready',source:'CEMADEN',stations:[{latitude:-10,longitude:-48,amount:0,statusLeitura:'valida',updatedAt:date,name:'Posto',fonte:'CEMADEN'}]};
let model=buildStateSituation({rain},features,now);
assert.equal(model.municipalities[0].indicators.rain.value,0);
assert.equal(model.municipalities[0].indicators.fire.value,null);
assert.equal(model.municipalities[0].coverage,1);
assert.equal(model.radar.find(r=>r.id==='rivers').status,'Dados insuficientes');
assert.equal(situationThemes.length,6);
model=buildStateSituation({rain:{...rain,stations:[{...rain.stations[0],amount:12}]},fire:{state:'ready',observedAt:date,points:[{latitude:-10,longitude:-48,detectedAt:date,satellite:'INPE'}]}},features,now);
assert.equal(model.municipalities[0].factor,'Múltiplos fatores');
assert.equal(model.municipalities[0].indicators.fire.value,1);
model=buildStateSituation({rain:{...rain,stations:[{...rain.stations[0],updatedAt:'2020-01-01T00:00:00Z'}]},alerts:{state:'ready',observedAt:date,inmetCount:1,details:[{title:'Chuva',location:'Teste',severity:'Perigo'}]}},features,now);
assert.equal(model.municipalities[0].indicators.rain.value,null);
assert.equal(model.municipalities[0].indicators.alerts.value,null,'Free-text geography is not confirmed municipal coverage');
assert.equal(model.radar.find(r=>r.id==='alerts').status,'Atenção elevada');
model=buildStateSituation({alerts:{state:'ready',observedAt:date,inmetCount:1,details:[{title:'Chuva',severity:'Perigo',municipalityCodes:['1']}]}},features,now);
assert.equal(model.municipalities[0].factor,'Alertas');
assert.equal(model.municipalities[0].indicators.alerts.value,1);
model=buildStateSituation({rivers:{hydrology:{rows:[{status:'ok',name:'Rio',latitude:-10,longitude:-48,readings:[{dateTime:date,level:100},{dateTime:new Date(now-86400000).toISOString(),level:100}]}]}}},features,now);
assert.equal(model.municipalities[0].indicators.rivers.value,0,'Stable measured levels retain coverage');
assert.equal(model.municipalities[0].coverage,1);
model=buildStateSituation({rain:{...rain,stations:[{...rain.stations[0],amount:-1}]}},features,now);
assert.equal(model.municipalities[0].indicators.rain.value,null);
console.log('State situation: zero, absence, freshness, spatial coverage, official alerts and non-composite integration passed.');
