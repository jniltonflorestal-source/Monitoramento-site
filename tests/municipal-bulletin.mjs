import assert from 'node:assert/strict';
import {buildMunicipalBulletin} from '../frontend/src/services/municipalBulletin.js';
const now=Date.parse('2026-10-11T12:00:00Z'),date=new Date(now).toISOString();
const feature={type:'Feature',properties:{codarea:'1',nome:'Teste'},geometry:{type:'Polygon',coordinates:[[[-49,-11],[-47,-11],[-47,-9],[-49,-9],[-49,-11]]]}};
let model=buildMunicipalBulletin({feature},now);
assert.equal(model.rain.maximum,null);
assert.equal(model.fire.count,null);
assert.equal(model.burned.hectares,null);
assert.equal(model.alerts.count,null);
const station={latitude:-10,longitude:-48,amount:0,statusLeitura:'valida',updatedAt:date,name:'Posto',source:'CEMADEN'};
model=buildMunicipalBulletin({feature,rain:[station,{...station,longitude:-52,amount:99},{...station,amount:30,updatedAt:'2020-01-01T00:00:00Z'}],fireHistory:{status:'ready',coverageStart:new Date(now-8*86400000).toISOString(),coverageEnd:date,updatedAt:date,points:[]},firePoints:[],burnedQuery:{state:'ready',data:{hectares:0,period:'09/2026'}}},now);
assert.equal(model.rain.maximum,0);
assert.equal(model.rain.rows.length,1);
assert.equal(model.fire.count,0);
assert.equal(model.burned.hectares,0);
model=buildMunicipalBulletin({feature,snapshot:{alerts:{state:'ready',observedAt:date,details:[{title:'Chuva',location:'Teste'}]}}},now);
assert.equal(model.alerts.count,null,'Free-text geography cannot confirm municipal alerts');
model=buildMunicipalBulletin({feature,snapshot:{alerts:{state:'ready',observedAt:date,details:[{title:'Chuva',municipalityCodes:['1']}]}}},now);
assert.equal(model.alerts.count,1);
assert.match(model.summary,/1 aviso/);
model=buildMunicipalBulletin({feature,rivers:[{code:'x',name:'Rio',latitude:-10,longitude:-48,collected:{status:'ok',readings:[{dateTime:date,level:100},{dateTime:new Date(now-86400000).toISOString(),level:90}]}}]},now);
assert.equal(model.rivers[0].level,100);
assert.equal(model.rivers[0].analysis.delta24.value,10);
assert.ok(!model.summary.includes('inundação'));
model=buildMunicipalBulletin({feature,rivers:[{code:'x',name:'Rio',latitude:-10,longitude:-48,collected:{status:'error',readings:[{dateTime:date,level:100}]}}]},now);
assert.match(model.rivers[0].status,/Consulta indisponível/);
console.log('Municipal bulletin: spatial scope, null/zero, freshness, coverage, alerts and deterministic summary passed.');
